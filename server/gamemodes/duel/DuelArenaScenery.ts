export function installDuelArenaScenery(services: Pick<GamemodeServerServices,"removeCollisionFlags">):void {
    // Generated by comparing complete native/clean SceneBuilder collision maps.
    // Only flags no longer supplied by any surviving object are removed.
    for (const tile of manifest.collision) services.removeCollisionFlags(tile.x,tile.y,tile.level,tile.removeFlags);
}
