import assert from "node:assert/strict";
import { DUEL_SHOP_PACKAGES, DUEL_SHOPKEEPER } from "../common/duel/DuelShop";
import { createDuelShopStore, isValidShopEmail } from "../game/duel/DuelShopStore";

const shop = createDuelShopStore();
let notifications = 0;
const unsubscribe = shop.subscribe(() => notifications++);
const initial = shop.getSnapshot();
assert.equal(shop.getSnapshot(), initial, "external-store snapshots remain stable");
assert.equal(shop.order("Alice", "alice@example.com"), false, "cannot order without review");
assert.equal(shop.review(), false, "closed shop cannot review");
shop.open();
assert.equal(shop.getSnapshot().open, true, "NPC and chat entrypoints can open the same shop");
assert.equal(shop.select("forged-product"), false, "unlisted product cannot enter order");
assert.equal(shop.select("platinum-100k"), true);
assert.equal(shop.review(), true);
assert.equal(shop.order("", "alice@example.com"), false, "draft must belong to a signed-in account");
assert.equal(shop.order("Alice", "invalid"), false, "draft requires valid email");
assert.equal(shop.order("Alice", " alice@example.com "), true);
const draft = shop.getSnapshot().draft!;
assert.deepEqual(draft, { account: "Alice", email: "alice@example.com", packageId: "platinum-100k", status: "awaiting-payment-setup" });
assert.equal(Object.isFrozen(draft), true);
assert.equal(shop.order("Alice", "alice@example.com"), false, "repeated order click cannot duplicate draft");
shop.close();
shop.open();
assert.equal(shop.getSnapshot().draft, draft, "draft survives closing in the same session");
shop.select("gold-10m");
assert.equal(shop.getSnapshot().draft, null, "changing package requires a fresh review");
assert.equal(shop.getSnapshot().stage, "browse");
shop.reset();
assert.deepEqual(shop.getSnapshot(), initial, "sign-out removes account-specific draft");
assert.ok(notifications > 5);
unsubscribe();
assert.equal(DUEL_SHOPKEEPER.wanderRadius, 0);
assert.ok(DUEL_SHOP_PACKAGES.every(product => Number.isSafeInteger(product.quantity) && product.quantity > 0));
assert.ok(DUEL_SHOP_PACKAGES.every(product => product.price === null), "unknown prices are never invented");
assert.equal(isValidShopEmail("alice@example.com"), true);
assert.equal(isValidShopEmail("a@@example.com"), false);
assert.equal(isValidShopEmail("a @example.com"), false);
console.log("duel shop: entrypoints, product validation, review, immutable session draft and account reset passed");
