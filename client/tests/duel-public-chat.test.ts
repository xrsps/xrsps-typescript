import assert from "node:assert/strict";
import { chatHistory } from "../rs/cs2/ChatHistory";
import { duelPublicChatStore } from "../game/duel/DuelPublicChatStore";
import { handleInboundUi } from "../network/serverConnection/handlers/inboundUi";
import { subscribeChatMessages } from "../network/serverConnection/subscriptions/ui";
import { applyStandalonePublicChat } from "../game/chat/StandalonePublicChat";
import { PlayerEcs } from "../game/ecs/PlayerEcs";
import { duelChatStore, createDuelChatEventBridge } from "../game/duel/DuelChatChannels";
import { createIdleDuelSnapshot } from "../common/duel/DuelProtocol";
import { executeDuelChatCommand } from "../game/duel/DuelChatCommands";
import { duelShopStore } from "../game/duel/DuelShopStore";
import { duelStore } from "../game/duel/DuelStore";
import { duelInteractionStore } from "../game/duel/DuelInteractionStore";

chatHistory.clear();
let updates = 0;
const unsubscribe = duelPublicChatStore.subscribe(() => updates++);
const empty = duelPublicChatStore.getSnapshot();
assert.equal(duelPublicChatStore.getSnapshot(), empty, "snapshots are stable between changes");
chatHistory.addMessage("private", "Private contents", "Other");
assert.equal(duelPublicChatStore.getSnapshot(), empty, "private messages never enter public conversation");
chatHistory.addMessage("public", "Hello courtyard", "Alice");
assert.deepEqual(duelPublicChatStore.getSnapshot().map(message => message.sender), ["Alice"]);
for (let index = 0; index < 105; index++) chatHistory.addMessage("public", `Message ${index}`, "Bob");
const bounded = duelPublicChatStore.getSnapshot();
assert.equal(bounded.length, 100);
assert.equal(bounded[0].text, "Message 5");
assert.equal(bounded[99].text, "Message 104");
assert.equal(Object.isFrozen(bounded), true);
chatHistory.addMessage("public", "<b>Plain text</b>", "Alice");
assert.equal(duelPublicChatStore.getSnapshot().at(-1)!.text, "<b>Plain text</b>", "history does not interpret HTML");
chatHistory.clear();
assert.equal(duelPublicChatStore.getSnapshot().length, 0, "logout clears conversation");
assert.ok(updates > 100);
unsubscribe();
let receivedType: number | undefined;
const stop = subscribeChatMessages(message => { receivedType = message.chatType; });
handleInboundUi({type:"chat",payload:{messageType:"public",chatType:1,from:"Alice",text:"Across the courtyard"}});
assert.equal(receivedType, 2, "standalone public packets use the existing public history channel");
handleInboundUi({type:"chat",payload:{messageType:"game",chatType:101,from:"Alice",text:"wishes to trade"}});
assert.equal(receivedType, 101, "clickable trade request type is preserved");
stop();
const players = new PlayerEcs(4), speaker = players.allocatePlayer(7), observer = players.allocatePlayer(8);
const speech = {messageType:"public",playerId:7,from:"Alice",text:"This is a sample"};
applyStandalonePublicChat(players, speech);
assert.equal(players.getOverheadChat(speaker)?.text, speech.text);
assert.equal(players.getOverheadChat(speaker)?.color, 0, "ordinary speech uses native yellow overhead colour");
assert.equal(players.getOverheadChat(observer), undefined, "speech is attached to the authenticated speaker only");
players.updateClient(149);
assert.equal(players.getOverheadChat(speaker)?.remaining, 1, "speech remains visible for almost three seconds");
players.updateClient(1);
assert.equal(players.getOverheadChat(speaker), undefined, "speech expires after 150 client cycles");
applyStandalonePublicChat(players, {...speech,playerId:99});
assert.equal(players.getIndexForServerId(99), undefined, "distant public text does not invent a visible player");
applyStandalonePublicChat(players, {...speech,messageType:"game"});
assert.equal(players.getOverheadChat(speaker), undefined, "game notices never impersonate player speech");
chatHistory.clear();
chatHistory.addMessage("public", "Hello", "Alice");
chatHistory.addMessage("game", "Bank updated.");
chatHistory.addMessage(4, "Bob wishes to trade with you.");
chatHistory.addMessage(16, "A duel is ready.");
chatHistory.addMessage("private", "Private contents");
assert.deepEqual(duelChatStore.getSnapshot().map(line=>line.channel), ["public","game","trade","duel"]);
assert.equal(duelChatStore.getSnapshot(), duelChatStore.getSnapshot(), "channel snapshots remain stable");
const events: Array<{type:number;text:string}> = [];
const bridge = createDuelChatEventBridge((type,text)=>events.push({type,text}));
const state = createIdleDuelSnapshot();
state.self = {id:7,name:"Alice",hp:99,maxHp:99,weaponId:5698,specialEnergy:100,ready:false};
state.requests = [{id:"request1",fromId:8,fromName:"Bob",weaponId:5698,expiresInTicks:99}];
state.tradeRequests = [{id:"trade1",fromId:9,fromName:"Carol",expiresInTicks:50}];
bridge(state); bridge(state);
assert.equal(events.filter(event=>event.type===103).length,1,"native challenge channel and no duplicate invitations");
assert.equal(events.filter(event=>event.type===101).length,1,"native trade request channel and no duplicate invitations");
duelShopStore.reset();
duelStore.reset();
assert.equal(executeDuelChatCommand("::shop"),false,"vanilla chat commands continue to the server");
assert.equal(executeDuelChatCommand("::exchange"),false,"duel exchange does not intercept vanilla commands");
assert.equal(duelShopStore.getSnapshot().open,false);
assert.equal(duelStore.update(state),true);
assert.equal(executeDuelChatCommand(" ::SHOP "),true);
assert.equal(duelShopStore.getSnapshot().open,true);
duelShopStore.reset();
assert.equal(executeDuelChatCommand("::shop now"),false,"only the exact shop command opens the shop");
assert.equal(executeDuelChatCommand("I like ::shop"),false,"public speech is not interpreted as a command");
assert.equal(duelShopStore.getSnapshot().open,false);
let exchangeOpened = 0;
const stopExchange = duelInteractionStore.subscribeExchange(() => exchangeOpened++);
assert.equal(executeDuelChatCommand("::exchange"),true,"duel players can open the local currency exchange");
assert.equal(exchangeOpened,1);
stopExchange();
duelStore.reset();
console.log("duel public chat: stable bounded history, privacy, clear, literal text and standalone channel normalization passed");
